const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch();
  try {
    for (const scheme of ['light', 'dark']) {
      const p = await browser.newPage({viewport: {width: 390, height: 844}, colorScheme: scheme});
      const errors = [];
      p.on('pageerror', e => errors.push(e.message));
      await p.goto('file://' + require('path').join(__dirname, 'ui', 'index.html'));
      await p.waitForTimeout(200);
      const saved = () => p.evaluate(() => JSON.parse(Android._notes));
      const count = async () => (await saved()).length;
      await p.click('#tile-notes');
      await p.waitForTimeout(150);
      assert.equal(await p.isVisible('#note-compose'), true, 'schrijfveld staat op het overzicht');
      assert.equal(await p.getAttribute('#s-notes .fab', 'aria-label'), 'Nieuwe lijst');
      const before = await count();
      await p.fill('#note-quick', '   \n  ');
      await p.click('#note-quick-save');
      assert.equal(await count(), before, 'lege notitie wordt niet bewaard');
      assert.equal(await p.evaluate(() => current), 'notes');
      await p.click('[data-scope="notes"]');
      assert.match(await p.textContent('#notes-list'), /Nog geen losse notities/);
      await p.click('[data-scope="lists"]');
      assert.equal(await p.locator('#notes-list .nrow').count(), 1, 'de bestaande boodschappenlijst blijft een lijst');
      await p.click('[data-scope="all"]');
      const text = 'Bellen met de garage\nMorgen om tien uur';
      await p.fill('#note-quick', text);
      await p.click('#note-quick-save');
      await p.waitForTimeout(100);
      assert.equal(await p.evaluate(() => current), 'notes', 'bewaren opent de notitie niet');
      assert.equal(await p.inputValue('#note-quick'), '');
      const made = (await saved()).find(n => n.text === text);
      assert.ok(made, 'de notitie staat opgeslagen');
      assert.equal(made.kind, 'note');
      assert.equal(made.title, '');
      assert.deepEqual(made.items, []);
      assert.equal(await p.textContent('#notes-total'), '1');
      assert.equal(await p.textContent('#notes-list-total'), '1');
      const row = p.locator('#notes-list [data-note-id="' + made.id + '"]');
      assert.match(await row.locator('.r1').innerText(), /Bellen met de garage/);
      assert.match(await row.locator('.r2').innerText(), /Morgen om tien uur/);
      assert.doesNotMatch(await row.locator('.r2').innerText(), /Bellen met de garage/);
      const hit = await p.evaluate(() => gsNotes('garage').items[0]);
      assert.equal(hit.title, 'Bellen met de garage');
      await p.fill('#notes-search', 'garage');
      assert.equal(await p.isVisible('#note-compose'), false, 'tijdens zoeken blijft het veld weg');
      await p.fill('#notes-search', '');
      assert.equal(await p.isVisible('#note-compose'), true);
      await row.click();
      await p.waitForTimeout(100);
      assert.equal(await p.evaluate(() => $('#s-note').classList.contains('kind-note')), true);
      assert.equal(await p.evaluate(() => $('#s-note .hdr h1').textContent), 'Notitie');
      assert.equal(await p.inputValue('#note-text'), text);
      assert.equal(await p.inputValue('#note-title'), '');
      assert.equal(await p.isVisible('#note-add'), false);
      assert.equal(await p.isVisible('#note-make-list'), true);
      assert.equal(await p.isVisible('.note-content-card'), false);
      assert.equal(await p.isVisible('#note-tab-children'), false);
      assert.equal(await p.isVisible('#note-list-location'), false);
      await p.evaluate(() => { const n = noteById(noteCur); n.items.push({id: 'spraak', text: 'Melk', done: false}); renderItems(); });
      assert.equal(await p.isVisible('.note-content-card'), true, 'ingesproken items bij een notitie blijven zichtbaar');
      assert.equal(await p.evaluate(() => noteKind(noteById(noteCur))), 'note');
      assert.equal(await p.isVisible('#note-text'), true);
      await p.evaluate(() => { const n = noteById(noteCur); n.items = []; renderItems(); });
      assert.equal(await p.isVisible('#note-make-list'), true);
      await p.click('#note-make-list');
      assert.equal(await p.isVisible('#note-add'), true);
      assert.equal(await p.evaluate(() => $('#s-note').classList.contains('kind-note')), false);
      assert.equal(await p.evaluate(() => noteById(noteCur).kind), 'list');
      assert.equal(await p.inputValue('#note-text'), text, 'de tekst blijft staan');
      assert.equal(await p.isVisible('#note-text'), true);
      await p.click('#s-note .back');
      await p.waitForTimeout(150);
      assert.equal(await p.evaluate(() => current), 'notes');
      await p.click('#s-notes .fab');
      await p.waitForTimeout(100);
      assert.equal(await p.evaluate(() => $('#s-note').classList.contains('kind-note')), false);
      assert.equal(await p.isVisible('#note-add'), true);
      assert.equal(await p.evaluate(() => noteById(noteCur).kind), 'list');
      await p.click('#s-note .back');
      await p.waitForTimeout(150);
      assert.equal((await saved()).some(n => !(n.title || '').trim() && !(n.text || '').trim() && !(n.items || []).length), false, 'lege lijst wordt niet bewaard');
      await p.waitForTimeout(800);
      const lang = 'Dit is een lange notitie zonder regeleinde zodat er geen teken verloren gaat bij het bewaren van de hele zin op deze telefoon vandaag';
      assert.ok(lang.length > 80);
      await p.fill('#note-quick', lang);
      await p.click('#note-quick-save');
      const longNote = (await saved()).find(n => n.text === lang);
      assert.ok(longNote, 'de hele zin is bewaard');
      assert.equal(longNote.title, '');
      await p.click('#notes-list [data-note-id="' + longNote.id + '"]');
      assert.equal(await p.inputValue('#note-text'), lang);
      await p.click('#s-note .back');
      await p.waitForTimeout(100);
      await p.evaluate(() => {
        notesGet().push({id: 'oud-tekst', title: '', text: 'Alleen tekst', items: [], updated: 1});
        notesSaveNow();
        renderNotes();
      });
      await p.click('#notes-list [data-note-id="oud-tekst"]');
      assert.equal(await p.evaluate(() => $('#s-note').classList.contains('kind-note')), true, 'oude tekst zonder kind opent als notitie');
      assert.equal(await p.isVisible('.note-content-card'), false);
      await p.click('#s-note .back');
      await p.evaluate(() => openNote('a1'));
      await p.waitForTimeout(80);
      assert.equal(await p.evaluate(() => $('#s-note').classList.contains('kind-note')), false, 'een bestaande lijst blijft een lijst');
      assert.equal(await p.isVisible('#note-text'), true);
      assert.equal(await p.isVisible('#note-add'), true);
      assert.equal(await p.isVisible('#note-panel-list'), true);
      await p.evaluate(() => noteShareNow());
      assert.equal(await p.getAttribute('#sheet-sub', 'translate'), 'no');
      assert.equal(await p.textContent('#sheet-sub'), 'Boodschappen');
      await p.evaluate(() => closeSheet());
      await p.click('#s-note .back');
      await p.setViewportSize({width: 320, height: 740});
      await p.waitForTimeout(100);
      assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, 'het overzicht past op een smal scherm');
      assert.deepEqual(errors, []);
      console.log(scheme, 'losse notities: errors []');
      await p.close();
    }
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
