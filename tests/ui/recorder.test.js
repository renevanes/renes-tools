const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch();
  try {
    for (const colorScheme of ['light', 'dark']) {
      const page = await browser.newPage({ viewport: { width: 390, height: 844 }, colorScheme });
      const errors = []; page.on('pageerror', e => errors.push(e.message));
      await page.goto('file://' + require('path').join(__dirname, 'ui', 'index.html'));
      await page.click('#tile-recorder');
      assert.equal(await page.isDisabled('#recorder-start'), true);
      assert.equal(await page.isChecked('#recorder-auto'), false, 'automatisch begint uit');
      await page.click('#recorder-auto');
      assert.equal(await page.isChecked('#recorder-auto'), false, 'zonder rechten geen automatische opname');
      assert.match(await page.textContent('#recorder-result'), /microfoon- en telefoontoegang/);
      assert.match(await page.textContent('#s-recorder'), /niet gegarandeerd/);
      assert.match(await page.textContent('#recorder-list'), /Nog geen opnames/);
      await page.click('#recorder-permissions');
      await page.waitForFunction(() => !document.querySelector('#recorder-start').disabled);
      assert.equal(await page.evaluate(() => Android._recorder.busy), false, 'toestemming begint geen opname');
      assert.equal(await page.isVisible('#recorder-access'), true);
      assert.match(await page.textContent('#recorder-access-state'), /staat uit/);
      await page.click('#recorder-auto');
      assert.equal(await page.isChecked('#recorder-auto'), false, 'zonder gedeelde spraakbron geen automatische stille opname');
      assert.match(await page.textContent('#recorder-result'), /hulp bij gespreksopname/);
      await page.click('#recorder-access-button');
      assert.equal(await page.evaluate(() => Android._recorder.accessSettingsOpened), true);
      assert.equal(await page.evaluate(() => Android._recorder.callAccess), false, 'instellingen openen geeft zichzelf geen toestemming');
      await page.evaluate(() => { Android._recorder.callAccess = true; loadRecorder(); });
      assert.match(await page.textContent('#recorder-access-state'), /is actief/);
      await page.check('#recorder-auto');
      assert.equal(await page.evaluate(() => Android._recorder.autoEnabled), true);
      assert.equal(await page.evaluate(() => Android._recorder.busy), false, 'inschakelen begint geen opname van een lopend gesprek');
      await page.click('#recorder-start');
      await page.waitForFunction(() => document.querySelector('#recorder-state').textContent.includes('Opname actief'));
      await page.evaluate(() => { Android._recorder.amplitude = 12345; loadRecorder(); });
      assert.equal(await page.locator('#recorder-level').evaluate(el => el.value), 12345);
      assert.equal(await page.isDisabled('#recorder-access-button'), true, 'geen service-instellingen veranderen tijdens opname');
      await page.evaluate(() => { Android._recorder.silent = true; Android._recorder.elapsed = 7000; loadRecorder(); });
      assert.equal(await page.isVisible('#recorder-warning'), true);
      await page.evaluate(() => { Android._recorder.silent = false; Android._recorder.silenced = true; loadRecorder(); });
      assert.equal(await page.isVisible('#recorder-warning'), true, 'Android-demping blijft zichtbaar na eerder hoorbaar geluid');
      assert.match(await page.textContent('#recorder-warning'), /Android dempt de microfoon/);
      assert.equal(await page.locator('#recorder-level').evaluate(el => el.value), 0, 'geen oud geluidsniveau tonen als Android dempt');
      assert.match(await page.textContent('#recorder-warning'), /opnamefunctie van je telefoon-app/);
      assert.equal(await page.evaluate(async () => {
        let changes = 0;
        const observer = new MutationObserver(() => changes++);
        observer.observe(document.querySelector('#recorder-warning'), {childList:true, characterData:true, subtree:true});
        loadRecorder(); loadRecorder();
        await Promise.resolve(); observer.disconnect(); return changes;
      }), 0, 'Een ongewijzigde statuswaarschuwing wordt niet elke seconde opnieuw voorgelezen');
      await page.evaluate(() => { Android._recorder.silenced = false; loadRecorder(); });
      assert.equal(await page.isVisible('#recorder-warning'), false, 'Na herstel geen verouderde dempingswaarschuwing');
      await page.uncheck('#recorder-auto');
      assert.equal(await page.evaluate(() => Android._recorder.recording), true, 'uitschakelen houdt een handmatige opname in stand');
      await page.evaluate(() => show('home'));
      assert.equal(await page.evaluate(() => Android._recorder.recording), true, 'navigeren stopt een opname niet');
      await page.click('#tile-recorder');
      await page.click('#recorder-stop');
      await page.waitForFunction(() => document.querySelectorAll('#recorder-list article').length === 1);
      assert.match(await page.textContent('#recorder-result'), /Opname opgeslagen/);
      assert.equal(await page.isVisible('#recorder-warning'), false, 'stiltewaarschuwing verdwijnt na stoppen');
      assert.equal(await page.isVisible('#recorder-meter'), false);
      assert.equal(await page.isDisabled('#recorder-list [data-action="export"]'), true);
      await page.click('#recorder-list [data-action="play"]');
      assert.ok(await page.evaluate(() => Android._recorder.playing));
      await page.click('#recorder-list [data-action="share"]');
      assert.ok(await page.evaluate(() => Android._recorder.shared));
      await page.evaluate(() => { Android._wa.info.dest = true; loadRecorder(); });
      await page.click('#recorder-list [data-action="export"]');
      await page.waitForFunction(() => document.querySelector('#recorder-result').textContent.includes('geëxporteerd'));
      assert.equal(await page.evaluate(() => Android._recorder.rows.length), 1, 'export bewaart lokale opname');
      await page.click('#recorder-list [data-action="delete"]'); await page.click('#modal-cancel');
      assert.equal(await page.locator('#recorder-list article').count(), 1);
      await page.click('#recorder-list [data-action="delete"]'); await page.click('#modal-ok');
      assert.equal(await page.locator('#recorder-list article').count(), 0);
      await page.evaluate(() => { Android._recorder.phone = false; Android._recorder.message = 'Opname niet opgeslagen: microfoon geblokkeerd'; loadRecorder(); });
      assert.match(await page.textContent('#recorder-phone'), /zelf stoppen/);
      assert.match(await page.textContent('#recorder-result'), /microfoon geblokkeerd/);
      await page.evaluate(() => { Object.assign(Android._recorder, {phone:true, autoEnabled:true, automatic:true, busy:true, recording:true}); loadRecorder(); });
      assert.match(await page.textContent('#recorder-state'), /Automatische opname actief/);
      await page.uncheck('#recorder-auto');
      assert.equal(await page.evaluate(() => Android._recorder.recording), false, 'uitschakelen stopt automatische opname');
      await page.evaluate(() => { Object.assign(Android._recorder, {phone:false, autoEnabled:true, message:'Android blokkeert automatisch opnemen. Open de app om handmatig te starten.'}); loadRecorder(); });
      assert.match(await page.textContent('#recorder-auto-state'), /toestemmingen.*meldingen.*ontbreken/);
      assert.match(await page.textContent('#recorder-result'), /handmatig te starten/);
      await page.evaluate(() => { Object.assign(Android._recorder, {phone:true, callAccessRequired:false, callAccess:false, autoEnabled:false}); loadRecorder(); });
      assert.equal(await page.isVisible('#recorder-access'), false, 'Op oudere Android-versies geen onnodige hulpdienst vragen');
      await page.check('#recorder-auto');
      assert.equal(await page.isChecked('#recorder-auto'), true, 'Oudere Android-versies behouden automatisch starten zonder nieuwe hulpdienst');
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
      await page.screenshot({ path: __dirname + '/shots/recorder-' + colorScheme + '.png' });
      assert.deepEqual(errors, []);
      console.log(colorScheme, 'toestemming, opname, stiltewaarschuwing, navigatie, afspelen, delen, export en wissen gecontroleerd');
      console.log('errors', errors);
      await page.close();
    }
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
